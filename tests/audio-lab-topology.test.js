const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=path.join(__dirname,'../experiments/audio-lab');
async function load(name){const source=fs.readFileSync(path.join(base,name),'utf8');return import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'))}
(async()=>{
 const {interpretTopology}=await load('topology-composition.js');
 const {TOPOLOGY_STUDIES}=await load('topology-fixtures.js');
 const results=TOPOLOGY_STUDIES.map(s=>interpretTopology(s.pieces));
 assert.equal(TOPOLOGY_STUDIES.length,3);
 assert.deepEqual(results.map(r=>r.features.tiles),[6,6,6]);
 assert.deepEqual(results.map(r=>r.features.cycles),[0,0,1]);
 assert.deepEqual(results.map(r=>r.features.junctions),[0,0,1]);
 assert.equal(results[0].features.corners,0);
 assert.ok(results[1].features.corners>=3);
 assert.deepEqual(results.map(r=>r.voices.length),[1,2,4]);
 assert.ok(results.every(r=>r.events.every(e=>e.pip>=0&&e.pip<=6&&e.beat>=0&&e.beat<8)));
 assert.ok(results.every(r=>r.events.length<=8+4+4+3));
 const original=structuredClone(TOPOLOGY_STUDIES[2].pieces);
 assert.deepEqual(interpretTopology(original),results[2]);
 assert.deepEqual(interpretTopology([...original].reverse().map(p=>({...p,connections:[...p.connections].reverse()}))),results[2]);
 assert.deepEqual(TOPOLOGY_STUDIES[2].pieces,original);
 const noConnections=original.map(p=>({...p,connections:[]}));
 assert.equal(interpretTopology(noConnections).features.edges,0);
 assert.equal(interpretTopology([]).voices.length,0);
 assert.throws(()=>interpretTopology([original[0],original[0]]),/duplicate/);
 assert.throws(()=>interpretTopology([{id:1,tile:{a:7,b:1},connections:[]}]),/printed/);
 assert.throws(()=>interpretTopology([{id:1,tile:{a:2,b:2},connections:[{toPieceId:999,fromSide:'R'}]}]),/neighbour/);
 const broken=structuredClone(original);broken[0].connections=[];
 assert.throws(()=>interpretTopology(broken),/reciprocal/);
 const html=fs.readFileSync(path.join(base,'topology-study.html'),'utf8');
 const entry=fs.readFileSync(path.join(base,'index.html'),'utf8');
 assert.match(html,/topology-composition\.js/);
 assert.match(html,/topology-fixtures\.js/);
 assert.match(html,/instrument\.js/);
 assert.match(html,/type="file"/);
 assert.match(entry,/topology-study\.html/);
 console.log('Audio Lab topology study regressions passed');
})().catch(e=>{console.error(e);process.exitCode=1});
