const assert=require('assert');
const fs=require('fs');
const path=require('path');
const C=require('../mode-carousel.js');

assert.strictEqual(C.MODES.length,8);
assert.deepStrictEqual(C.MODES.slice(0,2).map(m=>[m.id,m.available]),[['classic',true],['infinite-endless',true]]);
assert.strictEqual(C.MODES.slice(2).length,6);
assert(C.MODES.slice(2).every(m=>m.available===false&&m.description==='Not available'));
assert.strictEqual(C.clampIndex(-3),0);
assert.strictEqual(C.clampIndex(99),7);
assert.strictEqual(C.stepIndex(0,1),1);
assert.strictEqual(C.stepIndex(7,1),0,'the end of the carousel returns to Classic');
assert.strictEqual(C.stepIndex(0,-1),7,'the carousel remains circular in reverse');
assert.strictEqual(C.cyclicOffset(0,7),1,'Classic is the visible next neighbour after the final mode');
assert.strictEqual(C.cyclicOffset(7,0),-1,'the final mode remains the visible previous neighbour beside Classic');
const nearCenter=C.magnetizeDrag(12);
assert.ok(Math.abs(nearCenter)<12,'a tile close to centre is pulled inward');
const nearNext=C.magnetizeDrag(C.SPACING-16);
assert.ok(nearNext>C.SPACING-16&&nearNext<C.SPACING,'a tile close to the next centre is magnetised toward its snap point');
assert.strictEqual(C.magnetizeDrag(50),50,'free dragging remains direct outside the magnetic zone');
assert.strictEqual(C.SETTLE_APPROACH_MS,250);
assert.strictEqual(C.SETTLE_LAND_MS,140);
assert.strictEqual(C.SETTLE_MIN_APPROACH_MS,140);
assert.strictEqual(C.SETTLE_MIN_LAND_MS,70);
assert.strictEqual(C.SETTLE_MS,390);
assert.strictEqual(C.SETTLE_OVERSHOOT,8);
const settled=C.settleProfile(0,0),near=C.settleProfile(10,0),medium=C.settleProfile(45,0),far=C.settleProfile(C.SPACING,0);
assert.strictEqual(settled.overshoot,0,'exact centre has no synthetic bounce');
assert.ok(near.overshoot>0&&near.overshoot<1,'release near centre has only a tiny overshoot');
assert.ok(medium.overshoot>near.overshoot&&medium.overshoot<far.overshoot,'overshoot scales continuously with remaining travel');
assert.strictEqual(far.overshoot,C.SETTLE_OVERSHOOT,'full travel keeps the current maximum overshoot');
assert.ok(near.approachMs<medium.approachMs&&medium.approachMs<far.approachMs,'approach duration grows with release distance');
assert.ok(near.landMs<medium.landMs&&medium.landMs<far.landMs,'landing duration grows with release distance');
const src=fs.readFileSync(path.join(__dirname,'..','mode-carousel.js'),'utf8');
assert.match(src,/id='modeCarouselFrame'|frame\.id='modeCarouselFrame'/);
assert.match(src,/slides\[0\]\.id='modeClassic'/);
assert.match(src,/modeTileInfinite/);
assert.doesNotMatch(src,/modeCenterBounce/,'snap must not use a scale/click bounce');
assert.match(src,/\.isPulling \.modeSlide\{transition:translate var\(--settle-approach-ms/,'release timing must be adaptive');
assert.match(src,/\.isLanding \.modeSlide\{transition:translate var\(--settle-land-ms/,'landing timing must be adaptive');
assert.match(src,/overshootShift=targetShift\+direction\*profile\.overshoot/,'overshoot direction and amplitude must follow physical travel');
assert.match(src,/strength=t\*t\*\(3-2\*t\)/,'settle strength must ease down strongly near centre');
assert.match(src,/\.modeSlide\.isRemote\{visibility:hidden;pointer-events:none\}\.modeSlide\.isRemote \.modeTile\{visibility:visible\}/,'remote controls stay out of layout checks while their tile visuals remain physically pre-positioned');
assert.match(src,/\.isRebasing \.modeSlide\{transition:none!important\}/,'circular seam rebasing must happen offscreen without crossing the window');
assert.match(src,/startRun\.disabled=!mode\.available/);
assert.match(src,/ACTIVE_MODE_KEY/);
const gesture=fs.readFileSync(path.join(__dirname,'..','gesture.js'),'utf8');
assert.match(gesture,/mode-carousel\.js\?v=20260919\.5/);
assert.match(gesture,/data-monoid-modes/);
console.log('mode carousel adaptive physical settle regression tests passed');
